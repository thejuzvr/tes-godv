defmodule TesIdleWeb.ErrorJSON do
  @moduledoc """
  JSON-ошибки с TES-флейвором.

  Поле `detail` попадает в error-тосты фронтенда (api.ts читает `data.detail`),
  поэтому вместо сухого "Not Found" игрок видит строчку в духе мира.
  `message` — стандартный HTTP-статус, для логов/отладки.
  """

  @flavor %{
    "Not Found" => [
      "Такой дороги нет ни на одной карте Тамриэля. Даже картограф стыдливо молчит.",
      "Стражник развёл руками: «Не знаю такой страницы. И булочку с корицей не видел».",
      "Стрела в колене — больно. Запрос мимо маршрута — досадно.",
      "Свиток с такими словами не читается. Стража рекомендует сверить путь.",
    ],
    "Internal Server Error" => [
      "Сервер пал в бою, как истинный норд. Сага о возрождении уже пишется.",
      "Драугр-админ забыл завести реактор. Классика Скайрима.",
      "Альдуин налетел на дата-центр. Кузнецы уже в пути.",
    ],
    "Unauthorized" => [
      "Стража не пускает: «Документики не будет? Тогда и входа не будет».",
      "Thu'um без полномочий — это просто кашель. Предъяви токен.",
    ],
    "Forbidden" => [
      "Только Тейн и свита. Ты пока — не Тейн.",
      "Эти двери не для тебя, странник. Совет не одобрит.",
    ],
    "Too Many Requests" => [
      "Слишком часто стучишь в ворота. Стража предупреждает: последний раз.",
      "Дракон занят. Стучите позже — и реже.",
    ],
    "Bad Request" => [
      "Запрос прозвучал как кашель в Уиндхельме. Повтори внятнее.",
      "Голоса требуют переформулировать запрос по канону.",
    ],
  }

  def render(template, _assigns) do
    status_message = Phoenix.Controller.status_message_from_template(template)

    case Map.get(@flavor, status_message) do
      pool when is_list(pool) and pool != [] ->
        %{errors: %{detail: Enum.random(pool), message: status_message}}

      _ ->
        # Нестандартные статусы (402, 418, ...) — честный дефолт без флейвора
        %{errors: %{detail: status_message}}
    end
  end
end
