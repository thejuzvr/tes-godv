  def run do
    existing =
      Repo.all(from t in NarrativeTemplate, where: t.source == "system", select: {t.template_type, t.text_template})
      |> MapSet.new()

    inserted =
      Enum.reduce(@templates, 0, fn {type, text}, acc ->
        if MapSet.member?(existing, {type, text}) do
          acc
        else
          Repo.insert!(%NarrativeTemplate{
            template_type: type,
            text_template: text,
            source: "system",
            is_active: true
          })

          acc + 1
        end
      end)

    IO.puts("seed_narratives: шаблонов всего #{length(@templates)}, новых +#{inserted}")
  end

  # CD-1: отладочный доступ к списку для разовых скриптов
  def templates, do: @templates
end

