loc = fn name ->
  case Repo.get_by(Location, name: name) do
    nil ->
      IO.puts("!! локация не найдена, пропускаю: #{name}")
      nil

    l ->
      l.id
  end
end

# Статы по формуле существующей БД:
# hp ≈ 30+11×mid, atk_min ≈ 4+2×lo, atk_max ≈ 8+2.3×hi, def ≈ 1+0.8×mid,
# xp ≈ 10×mid, gold_min/max ≈ 2×mid / 5×mid
m = fn name, desc, lo, hi, loc_id ->
  mid = div(lo + hi, 2)

  %{
    name: name,
    description: desc,
    min_level: lo,
    max_level: hi,
    hp: 30 + 11 * mid,
    attack_min: 4 + 2 * lo,
    attack_max: trunc(8 + 2.3 * hi),
    defense: trunc(1 + 0.8 * mid),
    xp_reward: 10 * mid,
    gold_min: 2 * mid,
    gold_max: 5 * mid,
    is_active: true,
    location_id: loc_id
  }
end

