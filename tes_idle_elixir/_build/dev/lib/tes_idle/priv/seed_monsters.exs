  {"Дракон-новобранец", "Золотой слиток", 0.25}
]

loot_inserted =
  Enum.reduce(boss_loot, 0, fn {monster_name, item_name, chance}, acc ->
    monster =
      Repo.one(from mo in Monster, where: mo.name == ^monster_name, limit: 1)

    item = Repo.one(from i in Item, where: i.name == ^item_name, limit: 1)

    cond do
      is_nil(monster) or is_nil(item) ->
        IO.puts("!! лут пропущен: #{monster_name} → #{item_name}")
        acc

      Repo.one(
        from ml in MonsterLoot,
          where: ml.monster_id == ^monster.id and ml.item_id == ^item.id,
          limit: 1
      ) ->
        acc

      true ->
        Repo.insert!(%MonsterLoot{monster_id: monster.id, item_id: item.id, drop_chance: chance})
        acc + 1
    end
  end)

total = Repo.aggregate(Monster, :count, :id)
