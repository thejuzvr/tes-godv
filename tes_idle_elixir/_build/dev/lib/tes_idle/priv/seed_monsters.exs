{inserted, skipped} =
  Enum.reduce(roster, {0, 0}, fn {loc_name, monsters}, {ins, skip} ->
    case loc.(loc_name) do
      nil ->
        {ins, skip + length(monsters)}

      loc_id ->
        new_ins =
          Enum.reduce(monsters, 0, fn {name, desc, lo, hi}, acc ->
            exists = Repo.one(from mo in Monster, where: mo.name == ^name and mo.location_id == ^loc_id, limit: 1)

            if exists do
              acc
            else
              Repo.insert!(struct(Monster, m.(name, desc, lo, hi, loc_id)))
              acc + 1
            end
          end)

        {ins + new_ins, skip}
    end
  end)

# ── Лут боссам (MonsterLoot: drop_chance default 0.3) ──────────────────────────

boss_loot = [
  {"Драугр-владыка", "Золотой слиток", 0.25},
  {"Двемерский центурион", "Двемерский шестерень", 0.4},
